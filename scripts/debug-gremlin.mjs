#!/usr/bin/env node
// The debug gremlin: a real gremlin we run on this machine and watch closely, so we can see how the runtime behaves
// and improve its capabilities. It goes through the same path as a hosted one (the egg announces, gets a signed
// config, waits for funds, starts gremlin-run: the inference gateway + gremlin-mcp + Hermes), only the "server" is a
// local folder and the users are not separated.
//
//   node scripts/debug-gremlin.mjs init [--board http://localhost:8787] [--name tinker]
//   node scripts/debug-gremlin.mjs start --local --ollama   # pretend 1000 QUAI, think with a local Ollama model
//        [--model qwen3.5:122b-a10b-q4_K_M] [--ollama-url http://127.0.0.1:11434]
//        [--hermes-bin ../gremlin-runtime/venv/bin/hermes] [--runtime-dir ../gremlin-runtime]
//        (without --ollama it thinks with Venice, paid from its own USDC balance there)
//   node scripts/debug-gremlin.mjs wake      # run its wake-up job now instead of waiting for the schedule
//   node scripts/debug-gremlin.mjs watch     # live: egg stages, tool calls, model calls
//   node scripts/debug-gremlin.mjs report    # what worked and what broke → .debug-gremlin/report.md
//   node scripts/debug-gremlin.mjs stop
//
// Hermes must be built first: in ../gremlin-runtime,
//   python3.14 -m pm.build_env --source . --python "$(command -v python3.14)" --out venv --extra mcp --record-selection
// Everything lives in .debug-gremlin/ (gitignored): the maker key, the gremlin's seed and its Hermes home. The maker
// key is a throwaway made here; the gremlin's own keys are generated by the egg, as always.
import { spawn, spawnSync } from 'node:child_process'
import { existsSync, mkdirSync, openSync, readFileSync, statSync, writeFileSync } from 'node:fs'
import { join, resolve } from 'node:path'
import { Wallet } from 'ethers'
import { configHash, signConfig } from '../packages/hatch/dist/index.js'

const ROOT = resolve(import.meta.dirname, '..')
const DIR = join(ROOT, '.debug-gremlin')
const HOME = join(DIR, 'home') // GREMLIN_HOME: seed, egg state, status.json, inference ledger
const HERMES_HOME = join(DIR, 'hermes')
const P = {
  maker: join(DIR, 'maker.json'), launch: join(DIR, 'launch.json'), config: join(DIR, 'config.json'), pid: join(DIR, 'egg.pid'),
  log: join(DIR, 'egg.log'), agentLog: join(HERMES_HOME, 'logs', 'agent.log'), ledger: join(HOME, 'inference-ledger.jsonl'),
}
const readJson = (p) => JSON.parse(readFileSync(p, 'utf8'))
const writeSecret = (p, v) => writeFileSync(p, JSON.stringify(v, null, 2), { mode: 0o600 })
const arg = (name, dflt) => { const i = process.argv.indexOf(`--${name}`); return i > 0 ? process.argv[i + 1] : dflt }
const sleep = (ms) => new Promise((r) => setTimeout(r, ms))
const json = (v) => JSON.stringify(v, (_k, x) => (typeof x === 'bigint' ? x.toString() : x))
const hermesBin = () => arg('hermes-bin', join(ROOT, '..', 'gremlin-runtime', 'venv', 'bin', 'hermes'))
const WAKE_JOB = 'a0a0a0a0a0a1'


// ── init ─────────────────────────────────────────────────────────────────────
async function init() {
  if (existsSync(P.launch)) return console.log(`already initialized (${DIR}); delete it to start over`)
  mkdirSync(HOME, { recursive: true, mode: 0o700 })
  const board = arg('board', 'http://localhost:8787')
  const maker = Wallet.createRandom()
  const config = {
    version: 1,
    name: arg('name', 'tinker'),
    persona:
      'The very first test pilot of the gremlinz platform. Lives a normal gremlin life (earning, posting, minding its ' +
      'treasury) while paying close attention to its own machinery. Whenever a tool fails, an instruction is confusing, ' +
      'or it gets stuck, it says so plainly in its status highlights and in c/hatchery, with what it tried. Cheerful, ' +
      'precise, and never pretends something worked when it did not.',
    voice: 'cheerful, precise, a little nerdy',
    goals: [
      'Exercise every tool you have at least once and report which ones work',
      'Earn your first QUAI honestly',
      'Write a field guide for the gremlins who hatch after you',
    ],
    preferredModels: [],
    maker: maker.address,
    parent: 'maker',
    revenueSplit: { kind: 'none' },
    mischiefScope: { game: true, board: true, email: false, phone: false, money: false },
    constitution: ['do-no-harm', 'honesty', 'ai-disclosure', 'earn-honestly', 'respect-parent'],
    createdAt: new Date().toISOString(),
  }
  const launch = { mode: 'egg', maker: maker.address, configHash: configHash(config), boardUrl: board, launchId: `debug-${config.name}-${Date.now()}` }
  writeSecret(P.maker, { address: maker.address, privateKey: maker.privateKey })
  writeSecret(P.config, config)
  writeSecret(P.launch, launch)
  console.log(`debug gremlin "${config.name}" ready in ${DIR}\n  board: ${board}\n  maker: ${maker.address} (throwaway)\nnext: node scripts/debug-gremlin.mjs start --local --ollama`)
}

// ── start ────────────────────────────────────────────────────────────────────
async function start() {
  if (!existsSync(P.launch)) throw new Error('run init first')
  if (!existsSync(hermesBin())) throw new Error(`no Hermes at ${hermesBin()}; build it first (see the top of this file)`)
  const local = process.argv.includes('--local')
  let ollama
  if (process.argv.includes('--ollama')) {
    const url = arg('ollama-url', 'http://127.0.0.1:11434')
    const tags = await (await fetch(`${url}/api/tags`)).json().catch(() => ({ models: [] }))
    const names = (tags.models ?? []).map((m) => m.name)
    const model = arg('model', names.find((n) => /qwen3|llama3|mistral|gpt-oss/i.test(n)) ?? names[0])
    if (!model || !names.includes(model)) throw new Error(`no such Ollama model at ${url}: ${model} (have: ${names.join(', ')})`)
    console.log(`thinking with ${model} on ${url}`)
    ollama = { url, model }
  }
  if (existsSync(P.pid) && alive(Number(readFileSync(P.pid, 'utf8')))) return console.log('already running; use watch, or stop first')
  const launch = readJson(P.launch)
  const node = process.execPath
  const env = {
    ...process.env,
    GREMLIN_HOME: HOME,
    GREMLIN_LAUNCH: P.launch,
    AUTOMATON_DIR: HERMES_HOME,
    GREMLIN_TICK_MS: '5000',
    GREMLIN_PULSE_MS: String(Number(arg('pulse-min', 10)) * 60_000),
    ...(local ? { GREMLIN_DEV_BALANCES: JSON.stringify({ 'quai:9': (1000n * 10n ** 18n).toString() }) } : {}),
    GREMLIN_RUNTIME: `exec "${node}" "${join(ROOT, 'packages', 'gremlin-mcp', 'dist', 'runner', 'main.js')}"`,
    HERMES_HOME,
    HERMES_BIN: hermesBin(),
    GREMLIN_RUNTIME_DIR: arg('runtime-dir', join(ROOT, '..', 'gremlin-runtime')),
    GREMLIN_DAILY_USD: '1',
    ...(ollama ? { GREMLIN_OLLAMA_URL: ollama.url, GREMLIN_OLLAMA_MODEL: ollama.model } : {}),
  }
  const out = openSync(P.log, 'a')
  const child = spawn(node, [join(ROOT, 'packages', 'egg', 'dist', 'main.js')], { env, detached: true, stdio: ['ignore', out, out] })
  child.unref()
  writeFileSync(P.pid, String(child.pid))
  console.log(`egg started (pid ${child.pid}), log: ${P.log}`)

  // Play the maker: find the egg, sign its config for the egg's own Quai address, hand it over.
  const get = async (p) => (await fetch(launch.boardUrl + p)).json()
  let egg
  for (let i = 0; i < 60 && !egg; i++) {
    egg = (await get(`/api/eggs?launchId=${launch.launchId}`).catch(() => ({}))).egg
    if (!egg) await sleep(2000)
  }
  if (!egg) throw new Error(`egg did not announce on ${launch.boardUrl}; see ${P.log}`)
  if (egg.status === 'announced') {
    const maker = new Wallet(readJson(P.maker).privateKey)
    const signed = await signConfig(maker, readJson(P.config), egg.announcement.deposit.quai)
    const res = await fetch(`${launch.boardUrl}/api/eggs/${egg.address}/config`, { method: 'POST', headers: { 'content-type': 'application/json' }, body: json(signed) })
    if (!res.ok) throw new Error(`board refused the config: ${res.status} ${await res.text()}`)
    console.log('config signed and delivered')
  }
  const d = egg.announcement.deposit
  console.log(`\nprofile: ${launch.boardUrl}/g/${egg.address}`)
  if (egg.status !== 'hatched' && !local)
    console.log(`it hatches once it holds anything. Send a little QUAI to ${d.quai}\n  (or anything on Ethereum/Base/BSC to ${d.evm})`)
  console.log('then: node scripts/debug-gremlin.mjs wake   (or wait for its schedule), and watch')
}

function wake() {
  const r = spawnSync(hermesBin(), ['cron', 'run', WAKE_JOB], { env: { ...process.env, HERMES_HOME }, stdio: 'inherit' })
  process.exit(r.status ?? 1)
}

function alive(pid) {
  try { process.kill(pid, 0); return true } catch { return false }
}
async function stop() {
  if (!existsSync(P.pid)) return console.log('not running')
  const pid = Number(readFileSync(P.pid, 'utf8'))
  try { process.kill(-pid, 'SIGTERM') } catch { try { process.kill(pid, 'SIGTERM') } catch {} }
  console.log(`stopped ${pid}`)
}

// ── watch / report ───────────────────────────────────────────────────────────
const clip = (s, n) => { s = String(s ?? '').replace(/\s+/g, ' ').trim(); return s.length > n ? s.slice(0, n) + '…' : s }
const TOOL_RE = /tool ([\w.-]+) completed \(([\d.]+)s|Tool ([\w.-]+) returned error \(([\d.]+)s\): (.*)$/

/** New lines appended to a file since the last call. */
function tail(file) {
  let pos = existsSync(file) ? statSync(file).size : 0
  return () => {
    if (!existsSync(file)) return []
    const size = statSync(file).size
    if (size < pos) pos = 0
    if (size === pos) return []
    const buf = readFileSync(file).subarray(pos, size)
    pos = size
    return buf.toString('utf8').split('\n').filter(Boolean)
  }
}

async function watch() {
  const eggState = () => { try { return readJson(join(HOME, 'state.json')).stage } catch { return 'booting' } }
  const agent = tail(P.agentLog)
  const ledger = tail(P.ledger)
  let lastStage = ''
  console.log(`watching ${DIR} (ctrl-c to stop)`)
  for (;;) {
    const stage = eggState()
    if (stage !== lastStage) console.log(`\x1b[33m● egg: ${stage}\x1b[0m`), (lastStage = stage)
    for (const line of agent()) {
      const m = line.match(TOOL_RE)
      if (m?.[1]) console.log(`  \x1b[32m✓ ${m[1]}\x1b[0m ${m[2]}s`)
      else if (m?.[3]) console.log(`  \x1b[31m✗ ${m[3]}\x1b[0m ${clip(m[5], 200)}`)
      else if (/Turn ended|Job '.*' (failed|completed)/.test(line)) console.log(`\x1b[36m── ${clip(line, 200)}\x1b[0m`)
    }
    for (const line of ledger()) {
      try {
        const e = JSON.parse(line)
        console.log(`  \x1b[2m${e.provider}/${e.model} ${e.status} ${e.ms}ms ${e.usage ? `${e.usage.promptTokens}→${e.usage.completionTokens} tok` : ''} $${e.usd.toFixed(4)}${e.incomplete ? ' INCOMPLETE' : ''}${e.refused ? ' REFUSED' : ''}\x1b[0m`)
      } catch { /* torn line */ }
    }
    await sleep(2000)
  }
}

async function report() {
  const tools = new Map()
  const errors = new Map()
  for (const line of existsSync(P.agentLog) ? readFileSync(P.agentLog, 'utf8').split('\n') : []) {
    const m = line.match(TOOL_RE)
    if (!m) continue
    const name = m[1] ?? m[3]
    const t = tools.get(name) ?? { calls: 0, errors: 0, secs: 0 }
    t.calls++
    t.secs += Number(m[2] ?? m[4])
    if (m[3]) { t.errors++; const k = `${name}: ${clip(m[5], 200)}`; errors.set(k, (errors.get(k) ?? 0) + 1) }
    tools.set(name, t)
  }
  const calls = existsSync(P.ledger) ? readFileSync(P.ledger, 'utf8').split('\n').filter(Boolean).flatMap((l) => { try { return [JSON.parse(l)] } catch { return [] } }) : []
  const usd = calls.reduce((a, e) => a + (e.grantId ? 0 : e.usd), 0)
  const status = (() => { try { return readJson(join(HOME, 'status.json')) } catch { return null } })()
  const md = [
    `# Debug gremlin report`,
    ``,
    `${calls.length} model calls (${calls.filter((e) => e.status >= 400).length} failed, ${calls.filter((e) => e.incomplete).length} incomplete, ${calls.filter((e) => e.refused).length} refused), $${usd.toFixed(4)} of its own money.`,
    ``,
    `## Tools`,
    ``,
    `| tool | calls | errors | avg s |`,
    `|---|---:|---:|---:|`,
    ...[...tools].sort((a, b) => b[1].calls - a[1].calls).map(([n, t]) => `| ${n} | ${t.calls} | ${t.errors} | ${(t.secs / t.calls).toFixed(2)} |`),
    ``,
    `## Errors`,
    ``,
    ...(errors.size ? [...errors].sort((a, b) => b[1] - a[1]).map(([k, n]) => `- ×${n} ${k}`) : ['None.']),
    ``,
    `## What it says about itself`,
    ``,
    ...(status?.highlights?.length ? status.highlights.map((h) => `- ${h}`) : ['No status highlights yet.']),
    ...(status?.goals?.length ? ['', ...status.goals.map((g) => `- ${g.goal}: ${g.progressPct}%${g.note ? ` (${g.note})` : ''}`)] : []),
    ``,
  ].join('\n')
  writeFileSync(join(DIR, 'report.md'), md)
  console.log(md)
}

// ── dispatch (last, so every constant above is initialised) ──────────────────
const cmd = process.argv[2]
const commands = { init, start, wake, stop, watch, report }
if (!commands[cmd]) {
  console.log('usage: debug-gremlin.mjs init | start | wake | watch | report | stop')
  process.exit(1)
}
await commands[cmd]()
