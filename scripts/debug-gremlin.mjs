#!/usr/bin/env node
// The debug gremlin: a real gremlin we run on this machine and watch closely, so we can see how the runtime behaves
// and improve its capabilities. It goes through the same path as a hosted one (the egg supervisor announces, gets a
// signed config, waits for funds, starts the runtime, pulses), only the "server" is a local folder.
//
//   node scripts/debug-gremlin.mjs init [--board URL] [--name tinker] [--model claude-sonnet-5]
//   ANTHROPIC_API_KEY=… node scripts/debug-gremlin.mjs start     # egg + runtime in the background, hands it its config
//   node scripts/debug-gremlin.mjs start --local --ollama          # fully local: pretend 1000 QUAI, local Ollama model
//        [--model qwen3.5:122b-a10b-q4_K_M] [--ollama-url http://127.0.0.1:11434]
//   node scripts/debug-gremlin.mjs watch                         # live transcript: thinking, tool calls, errors
//   node scripts/debug-gremlin.mjs report                        # summary of what worked and what broke → report.md
//   node scripts/debug-gremlin.mjs stop
//
// Everything lives in .debug-gremlin/ (gitignored): the maker key, the gremlin's seed and runtime state. The maker
// key is a throwaway made here; the gremlin's own keys are generated by the egg, as always.
import { spawn } from 'node:child_process'
import { existsSync, mkdirSync, openSync, readFileSync, writeFileSync } from 'node:fs'
import { join, resolve } from 'node:path'
import { Wallet } from 'ethers'
import { configHash, signConfig } from '../packages/hatch/dist/index.js'

const ROOT = resolve(import.meta.dirname, '..')
const DIR = join(ROOT, '.debug-gremlin')
const HOME = join(DIR, 'home') // GREMLIN_HOME: seed, egg state, status.json
const USER = join(DIR, 'user') // $HOME for the runtime, so its ~/.automaton is isolated
const P = { maker: join(DIR, 'maker.json'), launch: join(DIR, 'launch.json'), config: join(DIR, 'config.json'), pid: join(DIR, 'egg.pid'), log: join(DIR, 'egg.log'), db: join(USER, '.automaton', 'state.db') }
const readJson = (p) => JSON.parse(readFileSync(p, 'utf8'))
const writeSecret = (p, v) => writeFileSync(p, JSON.stringify(v, null, 2), { mode: 0o600 })
const arg = (name, dflt) => { const i = process.argv.indexOf(`--${name}`); return i > 0 ? process.argv[i + 1] : dflt }
const sleep = (ms) => new Promise((r) => setTimeout(r, ms))
const json = (v) => JSON.stringify(v, (_k, x) => (typeof x === 'bigint' ? x.toString() : x))

const cmd = process.argv[2]
const commands = { init, start, stop, watch, report, _inject: inject }
if (!commands[cmd]) {
  console.log('usage: debug-gremlin.mjs init | start | watch | report | stop')
  process.exit(1)
}
await commands[cmd]()

// ── init ─────────────────────────────────────────────────────────────────────
async function init() {
  if (existsSync(P.launch)) return console.log(`already initialized (${DIR}); delete it to start over`)
  mkdirSync(HOME, { recursive: true, mode: 0o700 })
  mkdirSync(USER, { recursive: true, mode: 0o700 })
  const board = arg('board', 'http://localhost:8787')
  const maker = Wallet.createRandom()
  const config = {
    version: 1,
    name: arg('name', 'tinker'),
    persona:
      'The very first test pilot of the gremlinz platform. Lives a normal gremlin life (earning, posting, minding its ' +
      'treasury) while paying close attention to its own machinery. Whenever a tool fails, an instruction is confusing, ' +
      'or it gets stuck, it says so plainly in its status highlights and in c/hatchery, with what it tried. Cheerful, ' +
      'precise, and never pretends something worked when it did not.',
    voice: 'cheerful, precise, a little nerdy',
    goals: [
      'Exercise every tool you have at least once and report which ones work',
      'Earn your first QUAI honestly',
      'Write a field guide for the gremlins who hatch after you',
    ],
    preferredModels: [arg('model', 'claude-sonnet-5')],
    maker: maker.address,
    parent: 'maker',
    revenueSplit: { kind: 'none' },
    mischiefScope: { game: true, board: true, email: false, phone: false, money: false },
    constitution: ['do-no-harm', 'honesty', 'ai-disclosure', 'earn-honestly', 'respect-parent'],
    createdAt: new Date().toISOString(),
  }
  const launch = { mode: 'egg', maker: maker.address, configHash: configHash(config), boardUrl: board, launchId: `debug-${config.name}-${Date.now()}` }
  writeSecret(P.maker, { address: maker.address, privateKey: maker.privateKey })
  writeSecret(P.config, config)
  writeSecret(P.launch, launch)
  console.log(`debug gremlin "${config.name}" ready in ${DIR}\n  board: ${board}\n  maker: ${maker.address} (throwaway)\nnext: ANTHROPIC_API_KEY=… node scripts/debug-gremlin.mjs start`)
}

// ── start ────────────────────────────────────────────────────────────────────
async function start() {
  if (!existsSync(P.launch)) throw new Error('run init first')
  const local = process.argv.includes('--local')
  const ollama = process.argv.includes('--ollama')
  if (!ollama && !process.env.ANTHROPIC_API_KEY && !process.env.OPENAI_API_KEY) console.warn('warning: no ANTHROPIC_API_KEY/OPENAI_API_KEY and no --ollama; the runtime will only have Conway credits to think with')
  let ollamaModel
  if (ollama) {
    const url = arg('ollama-url', 'http://127.0.0.1:11434')
    const tags = await (await fetch(`${url}/api/tags`)).json().catch(() => ({ models: [] }))
    const names = (tags.models ?? []).map((m) => m.name)
    ollamaModel = arg('model', names.find((n) => /qwen3|llama3|mistral|gpt-oss/i.test(n)) ?? names[0])
    if (!ollamaModel || !names.includes(ollamaModel)) throw new Error(`no such Ollama model at ${url}: ${ollamaModel} (have: ${names.join(', ')})`)
    console.log(`thinking with ${ollamaModel} on ${url}`)
    process.env.DEBUG_OLLAMA_URL = url
    process.env.DEBUG_MODEL = ollamaModel
  }
  if (existsSync(P.pid) && alive(Number(readFileSync(P.pid, 'utf8')))) return console.log('already running; use watch, or stop first')
  const launch = readJson(P.launch)
  const node = process.execPath
  const runtime = join(ROOT, 'runtime', 'dist', 'index.js')
  const env = {
    ...process.env,
    HOME: USER,
    GREMLIN_HOME: HOME,
    GREMLIN_LAUNCH: P.launch,
    AUTOMATON_DIR: join(USER, '.automaton'),
    GREMLIN_TICK_MS: '5000',
    GREMLIN_PULSE_MS: String(Number(arg('pulse-min', 10)) * 60_000),
    ...(local ? { GREMLIN_DEV_BALANCES: JSON.stringify({ 'quai:9': (1000n * 10n ** 18n).toString() }) } : {}),
    GREMLIN_RUNTIME: `"${node}" "${runtime}" --gremlin-setup && "${node}" "${join(ROOT, 'scripts', 'debug-gremlin.mjs')}" _inject && exec "${node}" "${runtime}" --run`,
  }
  const out = openSync(P.log, 'a')
  const child = spawn(node, [join(ROOT, 'packages', 'egg', 'dist', 'main.js')], { env, detached: true, stdio: ['ignore', out, out] })
  child.unref()
  writeFileSync(P.pid, String(child.pid))
  console.log(`egg started (pid ${child.pid}), log: ${P.log}`)

  // Play the maker: find the egg, sign its config for the egg's own Quai address, hand it over.
  const get = async (p) => (await fetch(launch.boardUrl + p)).json()
  let egg
  for (let i = 0; i < 60 && !egg; i++) {
    egg = (await get(`/api/eggs?launchId=${launch.launchId}`).catch(() => ({}))).egg
    if (!egg) await sleep(2000)
  }
  if (!egg) throw new Error(`egg did not announce on ${launch.boardUrl}; see ${P.log}`)
  if (egg.status === 'announced') {
    const maker = new Wallet(readJson(P.maker).privateKey)
    const signed = await signConfig(maker, readJson(P.config), egg.announcement.deposit.quai)
    const res = await fetch(`${launch.boardUrl}/api/eggs/${egg.address}/config`, { method: 'POST', headers: { 'content-type': 'application/json' }, body: json(signed) })
    if (!res.ok) throw new Error(`board refused the config: ${res.status} ${await res.text()}`)
    console.log('config signed and delivered')
  }
  const d = egg.announcement.deposit
  console.log(`\nprofile: ${launch.boardUrl}/g/${egg.address}`)
  if (egg.status !== 'hatched' && !local)
    console.log(`it hatches once it holds anything. Send a little QUAI to ${d.quai}\n  (or anything on Ethereum/Base/BSC to ${d.evm})`)
  console.log('then: node scripts/debug-gremlin.mjs watch')
}

/** Runs inside GREMLIN_RUNTIME after --gremlin-setup: give the runtime our inference keys (the debug shortcut). */
async function inject() {
  const p = join(process.env.HOME, '.automaton', 'automaton.json')
  const c = readJson(p)
  if (process.env.ANTHROPIC_API_KEY) c.anthropicApiKey = process.env.ANTHROPIC_API_KEY
  if (process.env.OPENAI_API_KEY) c.openaiApiKey = process.env.OPENAI_API_KEY
  if (process.env.DEBUG_OLLAMA_URL) {
    c.ollamaBaseUrl = process.env.DEBUG_OLLAMA_URL
    c.inferenceModel = process.env.DEBUG_MODEL
  }
  writeSecret(p, c)
  console.log(`debug: inference configured (model ${c.inferenceModel}${c.ollamaBaseUrl ? ` via Ollama ${c.ollamaBaseUrl}` : ''})`)
}

function alive(pid) {
  try { process.kill(pid, 0); return true } catch { return false }
}
async function stop() {
  if (!existsSync(P.pid)) return console.log('not running')
  const pid = Number(readFileSync(P.pid, 'utf8'))
  try { process.kill(-pid, 'SIGTERM') } catch { try { process.kill(pid, 'SIGTERM') } catch {} }
  console.log(`stopped ${pid}`)
}

// ── watch / report ───────────────────────────────────────────────────────────
async function openDb() {
  const { DatabaseSync } = await import('node:sqlite')
  return new DatabaseSync(P.db, { readOnly: true })
}
const clip = (s, n) => { s = String(s ?? '').replace(/\s+/g, ' ').trim(); return s.length > n ? s.slice(0, n) + '…' : s }

async function watch() {
  const eggState = () => { try { return readJson(join(HOME, 'state.json')).stage } catch { return 'booting' } }
  let lastStage = ''
  let seen = new Set()
  console.log(`watching ${DIR} (ctrl-c to stop)`)
  for (;;) {
    const stage = eggState()
    if (stage !== lastStage) console.log(`\x1b[33m● egg: ${stage}\x1b[0m`), (lastStage = stage)
    if (existsSync(P.db)) {
      const db = await openDb()
      const turns = db.prepare('SELECT id, timestamp, state, input, input_source, thinking, cost_cents FROM turns ORDER BY timestamp DESC LIMIT 20').all().reverse()
      for (const t of turns) {
        if (seen.has(t.id)) continue
        seen.add(t.id)
        console.log(`\n\x1b[36m── ${t.timestamp} · ${t.state}${t.input_source ? ` · from ${t.input_source}` : ''} · ${t.cost_cents}¢\x1b[0m`)
        if (t.input) console.log(`\x1b[2min: ${clip(t.input, 300)}\x1b[0m`)
        if (t.thinking) console.log(clip(t.thinking, 600))
        for (const c of db.prepare('SELECT name, arguments, result, error, duration_ms FROM tool_calls WHERE turn_id = ? ORDER BY created_at').all(t.id))
          console.log(`  ${c.error ? '\x1b[31m✗' : '\x1b[32m✓'} ${c.name}\x1b[0m(${clip(c.arguments, 120)}) ${c.duration_ms}ms → ${clip(c.error ?? c.result, 200)}`)
      }
      db.close()
    }
    await sleep(3000)
  }
}

async function report() {
  if (!existsSync(P.db)) return console.log('no runtime state yet (has it hatched?)')
  const db = await openDb()
  const turns = db.prepare('SELECT COUNT(*) n, COALESCE(SUM(cost_cents),0) cost, MIN(timestamp) first, MAX(timestamp) last FROM turns').get()
  const tools = db.prepare("SELECT name, COUNT(*) calls, SUM(error IS NOT NULL AND error != '') errors, ROUND(AVG(duration_ms)) avg_ms FROM tool_calls GROUP BY name ORDER BY calls DESC").all()
  const errors = db.prepare("SELECT name, error, COUNT(*) n FROM tool_calls WHERE error IS NOT NULL AND error != '' GROUP BY name, error ORDER BY n DESC LIMIT 25").all()
  const status = (() => { try { return readJson(join(HOME, 'status.json')) } catch { return null } })()
  db.close()
  const md = [
    `# Debug gremlin report`,
    ``,
    `${turns.n} turns from ${turns.first ?? '—'} to ${turns.last ?? '—'}, $${(turns.cost / 100).toFixed(2)} of inference.`,
    ``,
    `## Tools`,
    ``,
    `| tool | calls | errors | avg ms |`,
    `|---|---:|---:|---:|`,
    ...tools.map((t) => `| ${t.name} | ${t.calls} | ${t.errors} | ${t.avg_ms} |`),
    ``,
    `## Errors`,
    ``,
    ...(errors.length ? errors.map((e) => `- **${e.name}** ×${e.n}: ${clip(e.error, 300)}`) : ['None.']),
    ``,
    `## What it says about itself`,
    ``,
    ...(status?.highlights?.length ? status.highlights.map((h) => `- ${h}`) : ['No status highlights yet.']),
    ...(status?.goals?.length ? ['', ...status.goals.map((g) => `- ${g.goal}: ${g.progressPct}%${g.note ? ` (${g.note})` : ''}`)] : []),
    ``,
  ].join('\n')
  writeFileSync(join(DIR, 'report.md'), md)
  console.log(md)
}
